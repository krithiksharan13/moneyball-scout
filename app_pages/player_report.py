import pandas as pd
import plotly.graph_objects as go
import streamlit as st

import report
import scout
import ui

players = ui.load_players()
seasons = sorted(players.season.unique(), reverse=True)

st.title("📝 Scouting Report")

c1, c2 = st.columns([1, 2])
default_season = st.session_state.get("report_season", seasons[0])
season = c1.selectbox("Season", seasons, index=seasons.index(default_season), format_func=ui.season_label)
with c2:
    p = ui.player_picker(players, season, key="report_player", default_name="Adrián Liso")

head_img, head_text = st.columns([1, 5])
if isinstance(p.image_url, str):
    head_img.image(p.image_url, width=110)
contract = "–" if pd.isna(p.contract_expiration_date) else pd.Timestamp(p.contract_expiration_date).strftime("%b %Y")
head_text.markdown(f"## {p.tm_name}\n{p.team} · {p.league} · {p.sub_position} · age {p.age:.1f} · "
                   f"{p.country_of_citizenship} · contract until {contract}")

m1, m2, m3, m4 = st.columns(4)
m1.metric("Market value", ui.eur(p.value_eur))
m2.metric("Model value", ui.eur(p.pred_value_eur), f"{(p.gap_ratio - 1) * 100:+.0f}% vs market")
m3.metric("Minutes", f"{int(p.minutes):,}", f"{p.minutes_share * 100:.0f}% of team minutes", delta_color="off")
m4.metric("Goals + assists", f"{int(p.goals)} + {int(p.assists)}", f"npxG {p.npxG:.1f} · xA {p.xA:.1f}", delta_color="off")

left, right = st.columns(2)
with left:
    st.subheader("Profile")
    st.caption(f"Percentiles vs {p.position.lower()}s in {ui.season_label(season)}")
    st.plotly_chart(ui.radar([p], [p.tm_name]), width="stretch")
with right:
    st.subheader("Market value vs model value")
    hist = players[players.player_id == p.player_id].sort_values("season")
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=hist.season_label, y=hist.value_eur, name="Market", mode="lines+markers",
                             line=dict(color=ui.MUTED)))
    fig.add_trace(go.Scatter(x=hist.season_label, y=hist.pred_value_eur, name="Model", mode="lines+markers",
                             line=dict(color=ui.ACCENT)))
    fig.update_layout(height=380, margin=dict(t=30), yaxis=dict(title="€", tickformat="~s"),
                      legend=dict(orientation="h", y=-0.15, x=0.5, xanchor="center"))
    st.plotly_chart(fig, width="stretch")

st.divider()
st.subheader("AI scouting report")
try:
    api_key = st.secrets.get("GEMINI_API_KEY", "")
except FileNotFoundError:  # no secrets file at all
    api_key = ""
cache = st.session_state.setdefault("reports", {})
key = (int(p.player_id), int(season))

if key in cache:
    st.markdown(cache[key])
elif not api_key:
    st.info("Add `GEMINI_API_KEY` to `.streamlit/secrets.toml` to enable AI scouting reports.")
elif st.button("Generate report", type="primary"):
    similar = scout.similar_players(players, int(p.player_id), season, n=5)
    try:
        text = st.write_stream(report.stream_report(api_key, report.build_prompt(p, similar)))
        cache[key] = text
    except report.ReportError as e:
        st.error(f"Couldn't generate the report. {e}")
st.caption("Reports are generated by Gemini from the numbers on this page only. Treat them as a starting point, not a verdict.")
